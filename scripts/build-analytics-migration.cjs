// Builds the single installation script for projects already on v13.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const destination = 'supabase/migration_v14_v15_analytics_complete.sql';
function buildMigration() {
  const sections = ['migration_v14_analytics_composition.sql', 'migration_v15_analytics_components.sql'].map(file => {
    const sql = fs.readFileSync(path.join(root, 'supabase', file), 'utf8').replace(/\r\n/g, '\n');
    if ((sql.match(/^BEGIN;$/gm) || []).length !== 1 || (sql.match(/^COMMIT;$/gm) || []).length !== 1)
      throw Error(`Unexpected transaction boundaries in ${file}`);
    return `-- Source: ${file}\n${sql.replace(/^BEGIN;\n/m, '').replace(/^COMMIT;\s*$/m, '').trim()}\n`;
  });
  return `-- Generated by node scripts/build-analytics-migration.cjs; edit the source migrations.
-- For a project whose last applied migration is v13: run THIS ENTIRE FILE once.
-- Includes v14 + v15 in one transaction; no separate execution is needed.
-- Adds reporting functions only. Safe to reapply; keeps older reporting RPCs.
BEGIN;
DO $prerequisite$
BEGIN
 IF to_regprocedure('public.analytics_claim_jobs(uuid,integer)') IS NULL THEN
  RAISE EXCEPTION 'Apply migration_v13_analytics_parallel.sql before this script';
 END IF;
END
$prerequisite$;

${sections.join('\n')}
-- Deliver the schema reload only after the complete transaction commits.
NOTIFY pgrst, 'reload schema';
COMMIT;
`;
}
if (require.main === module) {
  fs.writeFileSync(path.join(root, destination), buildMigration());
  console.log(destination);
}
module.exports = { buildMigration };
